// Copies the plugin's files into src/wp-plugin-files.js so the Worker can serve the ZIP
// (/downloads/xkey-seo-fixer.zip). Run after changing the plugin:  node wordpress-plugin/bundle.mjs
// (test/check.mjs fails if the bundle is out of date).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const here = path.dirname(fileURLToPath(import.meta.url)), root = path.join(here, "xkey-seo-fixer");
const files = {};
const walk = (d) => { for (const f of fs.readdirSync(d).sort()) { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else files["xkey-seo-fixer/" + path.relative(root, p).split(path.sep).join("/")] = fs.readFileSync(p, "utf8"); } };
walk(root);
export const bundle = `// Generated by wordpress-plugin/bundle.mjs – don't edit; change wordpress-plugin/xkey-seo-fixer/ instead.\nexport const WP_FILES = ${JSON.stringify(files, null, 1)};\n`;
if (process.argv[1] === fileURLToPath(import.meta.url)) { fs.writeFileSync(path.join(here, "../src/wp-plugin-files.js"), bundle); console.log(`${Object.keys(files).length} files bundled`); }
