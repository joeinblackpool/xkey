"""Subset the two self-hosted fonts and write src/fonts.js (base64, served by the Worker at /fonts/…).

Sources (SIL Open Font License, licences in this folder):
  Fraunces    – npm @fontsource-variable/fraunces, files/fraunces-latin-full-normal.woff2
  Geist Mono  – npm geist, dist/fonts/geist-mono/GeistMono-Variable.ttf
Run:  pip install fonttools brotli && python fonts/build.py FRAUNCES_SRC GEISTMONO_SRC
Fraunces is pinned to SOFT 0, WONK 0, opsz 72 (weights 500–900); Geist Mono keeps weights 400–700.
Only Latin-1 plus common punctuation is kept, so each file stays small (≈32 KB and ≈14 KB).
"""
import base64, hashlib, os, sys
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

HERE = os.path.dirname(os.path.abspath(__file__))
UNICODES = "U+0020-007E,U+00A0-00FF,U+0131,U+0152-0153,U+2013-2014,U+2018-201A,U+201C-201E,U+2022,U+2026,U+2039-203A,U+20AC,U+2122,U+2192,U+2212"

def build(src, name, limits):
    font = TTFont(src)
    o = subset.Options()
    o.layout_features = ["kern", "liga", "calt", "ccmp", "locl", "mark", "mkmk", "tnum"]
    o.name_IDs = ["*"]; o.notdef_outline = True; o.hinting = False
    s = subset.Subsetter(o); s.populate(unicodes=subset.parse_unicodes(UNICODES)); s.subset(font)
    font = instancer.instantiateVariableFont(font, limits)
    font.flavor = "woff2"
    out = os.path.join(HERE, name + ".woff2")
    font.save(out)
    data = open(out, "rb").read()
    print(f"{name}.woff2 {len(data)} bytes")
    return data

def main(fraunces, geist):
    files = {
        "fraunces": build(fraunces, "fraunces", {"wght": (500, 900), "SOFT": 0, "WONK": 0, "opsz": 72}),
        "geist-mono": build(geist, "geist-mono", {"wght": (400, 700)}),
    }
    lines = ["// Generated by fonts/build.py – do not edit. Self-hosted WOFF2 fonts (SIL OFL, see fonts/).",
             "// Paths carry a content hash so they can be cached forever."]
    paths = {}
    for name, data in files.items():
        h = hashlib.sha256(data).hexdigest()[:10]
        paths[name] = f"/fonts/{name}-{h}.woff2"
    lines.append("export const FONT_PATHS = " + repr(paths).replace("'", '"') + ";")
    lines.append("export const FONT_FILES = {")
    for name, data in files.items():
        lines.append(f'  "{paths[name]}": "{base64.b64encode(data).decode()}",')
    lines.append("};")
    open(os.path.join(HERE, "..", "src", "fonts.js"), "w").write("\n".join(lines) + "\n")

if __name__ == "__main__":
    main(*sys.argv[1:3])
